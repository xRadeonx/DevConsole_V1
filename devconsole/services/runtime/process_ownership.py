"""Ownership verification and the confidence model (roadmap phase 0B.5).

This module answers exactly one question: *may this process be considered a
DevConsole-managed service?*  The answer is graded, and the grading is
deliberately conservative.

Grades
------
``HIGH``
    ``configured_port`` is listened on by this PID **and** ``cwd`` resolves to
    the expected service directory **and** ``cmdline`` matches the expected
    launch command for the service type **and** ``exe`` is a plausible runtime
    **and** workspace lineage is proven — with no contradictory evidence.
    Only ``HIGH`` may ever authorise a future destructive action.

``MEDIUM``
    All the primary evidence except lineage aligns.

``LOW``
    Only ``cwd`` aligns, or only the pair (port, command) aligns without a
    proven location.

``NONE``
    Anything else — including every hard rejection below.  This is the default.

Hard rejections (always ``NONE``, regardless of how much else matches)
---------------------------------------------------------------------
* no PID, or PID 1, or our own PID (self-kill guard);
* ``cwd`` unreadable or outside ``BASE_DIR``;
* ``cwd`` inside ``BASE_DIR`` but pointing at a *different* service directory;
* expected service directory missing;
* the candidate is a known critical process (DevConsole itself, systemd, a
  terminal emulator, a shell);
* ``port`` matches while ``cwd`` points elsewhere (contradiction);
* a kernel thread (no cmdline and no exe).

No rule promotes ``LOW``/``MEDIUM`` to ``HIGH``; ``HIGH`` is only ever
assembled directly from primary evidence.
"""

from __future__ import annotations

import enum
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

from devconsole.services.runtime.process_identity import (
    Confidence,
    ProcessFacts,
    ServiceDescriptor,
    ServiceType,
)

# --------------------------------------------------------------------------- #
# expected command shapes
# --------------------------------------------------------------------------- #

#: Trailing version marker of a versioned binary name (``node-22``, ``python3.11``).
#:
#: The allowlists below name the **runtime**, not one of its versions, so the
#: suffix is stripped before matching (see
#: :func:`normalize_executable_basename`).  Only a *numeric* suffix is removed:
#: ``nodefoo`` stays ``nodefoo`` and cannot reach an allowlist.
_VERSION_SUFFIX = re.compile(r"[-.]\d+(?:\.\d+)*$")

#: Basenames acceptable as the runtime of a DevConsole-managed process.
#:
#: Matched against the **normalized** basename, so both spellings of the same
#: runtime are accepted: ``python3.11``/``python3``/``python`` and
#: ``node-22``/``node``.
_ALLOWED_EXECUTABLES: dict[ServiceType, re.Pattern[str]] = {
    ServiceType.BACKEND: re.compile(
        r"^(python3?(\.\d+)?|pipenv|daphne|uvicorn|gunicorn|bash|sh)$"),
    ServiceType.FRONTEND: re.compile(
        r"^(node|npm|npx|yarn|pnpm|bun|webpack|concurrently|bash|sh)$"),
    ServiceType.AUXILIARY: re.compile(
        r"^(python3?(\.\d+)?|pipenv|celery|bash|sh)$"),
    ServiceType.UNKNOWN: re.compile(r"^$"),  # nothing is acceptable
}

#: Substrings that must appear in cmdline, per service type.
_COMMAND_PATTERNS: dict[ServiceType, tuple[tuple[str, ...], ...]] = {
    # Django dev server, as launched by tilix_runner.sh:156
    #   <pipenv> run python manage.py runserver 0.0.0.0:<port>
    ServiceType.BACKEND: (
        ("manage.py", "runserver"),
        ("daphne",),
    ),
    # Webpack dev server, as launched by tilix_runner.sh:268 (`npm start`)
    # which expands to `webpack serve --config webpack.config.js`.
    #
    # NOTE: `("webpack",)` is deliberately **not** listed here.  `_argv_contains`
    # matches substrings, so that entry would also accept
    # `cp webpack.config.js /tmp` or `webpacker build` as command evidence — a
    # real widening the 3F-ID differential caught.  The rewritten title is
    # handled precisely by ``_PROCESS_TITLE_COMMANDS`` instead.
    ServiceType.FRONTEND: (
        ("webpack", "serve"),
        ("npm", "start"),
        ("npm", "run", "start"),
        ("concurrently",),
        ("node", "webpack"),
    ),
    # Auxiliary consoles generated by tilix_service.py.
    ServiceType.AUXILIARY: (
        ("celery",),
        ("start_consumer",),
        ("pipenv",),
    ),
    ServiceType.UNKNOWN: (),
}

#: Commands whose *process title* is the only surviving evidence.
#:
#: ``webpack-dev-server`` renames itself, so by the time it is listening its argv
#: is literally ``["webpack"]``: the ``webpack serve --config …`` command line the
#: patterns above look for no longer exists anywhere in ``/proc``.  Fase 3
#: measured all 10 frontends stuck at MEDIUM for exactly this reason.
#:
#: Matched against ``argv[0]`` as a **whole token**, never as a substring, so
#: ``webpacker build`` or ``cp webpack.config.js /tmp`` are not mistaken for it.
_PROCESS_TITLE_COMMANDS: dict[ServiceType, frozenset[str]] = {
    ServiceType.FRONTEND: frozenset({"webpack"}),
}

#: cmdline fragments that prove DevConsole/workspace lineage.
_LINEAGE_HINTS = (
    "tilix_runner.sh",
    "start_tilix.sh",
    "switch_env.sh",
)

#: Command fragments that identify infrastructure that must never be classified
#: as a managed microservice, even if its cwd somehow falls inside BASE_DIR.
_CRITICAL_COMMAND_HINTS = (
    "dashboard.py",
    "devconsole.server",
    "systemd --user",
    "tilix --gapplication-service",
    "--gapplication-service",
)


class RejectionReason(str, enum.Enum):
    """Why a candidate was rejected outright (always yields ``NONE``)."""

    NO_CANDIDATE = "no_candidate_pid"
    SELF_KILL_GUARD = "candidate_is_this_process"
    PID_ONE = "candidate_is_pid_1"
    CRITICAL_PROCESS = "candidate_is_critical_infrastructure"
    CWD_UNREADABLE = "cwd_unreadable"
    CWD_OUTSIDE_BASE_DIR = "cwd_outside_base_dir"
    CWD_WRONG_SERVICE = "cwd_is_a_different_service"
    EXPECTED_DIR_MISSING = "expected_service_dir_missing"
    UNKNOWN_SERVICE_TYPE = "unknown_service_type"
    KERNEL_THREAD = "kernel_thread_no_cmdline_or_exe"
    CONTRADICTORY_EVIDENCE = "contradictory_evidence_port_vs_cwd"
    PROCESS_DISAPPEARED = "process_disappeared_during_inspection"
    PID_REUSED = "pid_start_time_mismatch"
    AMBIGUOUS_CANDIDATES = "multiple_ambiguous_candidate_pids"


@dataclass(frozen=True)
class OwnershipVerdict:
    """Outcome of ownership verification for one candidate."""

    confidence: Confidence
    owned: bool
    executable_matches: bool
    cwd_matches: bool
    port_matches: bool
    command_matches: bool
    ancestry_matches: bool
    evidence: tuple[str, ...]
    rejection_reason: str | None = None

    @property
    def allows_destructive_action(self) -> bool:
        return self.confidence.allows_destructive_action() and self.owned


def _argv_contains(argv: Sequence[str], needles: Iterable[str]) -> bool:
    """Return ``True`` if every needle appears (case-insensitive) in any argv token."""
    lowered = [a.lower() for a in argv]
    joined = " ".join(lowered)
    return all(n.lower() in joined for n in needles)


def command_matches_type(argv: Sequence[str], service_type: ServiceType) -> bool:
    """Does ``argv`` look like the expected launch command for this type?

    Two independent kinds of evidence, both fail-closed:

    * substring patterns over the whole command line (``_COMMAND_PATTERNS``), and
    * exact ``argv[0]`` process titles (``_PROCESS_TITLE_COMMANDS``) for programs
      that rename themselves and destroy the original command line.
    """
    if not argv:
        return False
    patterns = _COMMAND_PATTERNS.get(service_type, ())
    if any(_argv_contains(argv, needles) for needles in patterns):
        return True

    titles = _PROCESS_TITLE_COMMANDS.get(service_type, frozenset())
    if not titles:
        return False
    # Whole-token comparison on argv[0] only: a substring rule here would accept
    # "webpacker" or a path merely containing "webpack".
    return Path(argv[0]).name.split(" (", 1)[0].lower() in titles


def normalize_executable_basename(basename: str) -> str:
    """Strip a trailing numeric version marker from a binary name.

    Exists because distributions ship versioned runtime binaries and symlink the
    generic name to them: Fedora installs ``/usr/bin/node-22`` (with ``node`` as a
    symlink) and Python as ``python3.11``.  The allowlists name the runtime, so
    ``node-22`` must be judged as ``node`` — otherwise no Node service on such a
    system can ever be graded above MEDIUM.

    Only a numeric ``-<n>[.<n>…]`` suffix is removed, so an unrelated name such as
    ``nodefoo`` is left untouched and still cannot match an allowlist.
    """
    return _VERSION_SUFFIX.sub("", basename)


def executable_matches_type(executable: str | None, service_type: ServiceType) -> bool:
    """Is ``executable`` a plausible runtime for this type?

    Matches on the version-normalized basename: ``/usr/bin/node-22`` is graded as
    ``node`` and ``python3.11`` as ``python3``.
    """
    if not executable:
        return False
    basename = Path(executable).name.split(" (", 1)[0]
    pattern = _ALLOWED_EXECUTABLES.get(service_type)
    return bool(pattern and pattern.match(normalize_executable_basename(basename)))


class OwnershipVerifier:
    """Grades how strongly a candidate process belongs to this DevConsole workspace.

    Parameters
    ----------
    base_dir:
        The workspace root every managed process must live under.
    require_ancestry_for_high:
        When ``True`` (default) workspace lineage is required for ``HIGH``.
        Set to ``False`` only in tests that specifically exercise the
        ancestry-not-required grading.
    """

    def __init__(
        self,
        base_dir: Path | str,
        *,
        require_ancestry_for_high: bool = True,
        protected_pids: Iterable[int] = (),
    ) -> None:
        self.base_dir = Path(base_dir)
        try:
            self.base_dir_resolved = self.base_dir.resolve()
        except OSError:
            self.base_dir_resolved = self.base_dir
        self.require_ancestry_for_high = require_ancestry_for_high
        self.protected_pids = {int(p) for p in protected_pids} | {os.getpid()}

    # ------------------------------------------------------------------ #
    # helpers
    # ------------------------------------------------------------------ #

    def _resolve(self, path: str | Path | None) -> Path | None:
        if not path:
            return None
        try:
            return Path(path).resolve()
        except OSError:
            return None

    def _is_under(self, candidate: Path | None, ancestor: Path | None) -> bool:
        if candidate is None or ancestor is None:
            return False
        try:
            candidate.relative_to(ancestor)
            return True
        except ValueError:
            return False

    # ------------------------------------------------------------------ #
    # lineage
    # ------------------------------------------------------------------ #

    def ancestry_proves_workspace(
        self,
        *,
        self_argv: Sequence[str],
        ancestors: Sequence[tuple[Sequence[str], str | None]],
    ) -> bool:
        """Prove the candidate descends from this workspace.

        Satisfied when the candidate's own argv references a workspace script
        (``tilix_runner.sh`` and friends) or the workspace root, or when any
        *ancestor* does either, or when an ancestor's cwd lives under
        ``BASE_DIR``.

        The candidate's own ``cwd`` is deliberately **not** used here: location
        is already graded separately, and reusing it would make lineage vacuous.
        """
        joined_self = " ".join(self_argv).lower()
        if any(hint in joined_self for hint in _LINEAGE_HINTS):
            return True
        if str(self.base_dir_resolved).lower() in joined_self:
            return True

        for argv, cwd in ancestors:
            joined = " ".join(argv).lower()
            if any(hint in joined for hint in _LINEAGE_HINTS):
                return True
            if str(self.base_dir_resolved).lower() in joined:
                return True
            if self._is_under(self._resolve(cwd), self.base_dir_resolved):
                return True
        return False

    # ------------------------------------------------------------------ #
    # main entry point
    # ------------------------------------------------------------------ #

    def _hard_rejection(
        self,
        descriptor: ServiceDescriptor,
        facts: ProcessFacts,
        cwd: Path | None,
        expected_dir: Path | None,
        *,
        port_matches: bool,
    ) -> RejectionReason | None:
        """Return the first blocking condition, or ``None`` if none applies.

        Ordering is by severity: the earlier a condition is checked, the more
        fundamental the reason to refuse.
        """
        if not facts.pid or facts.pid <= 0:
            return RejectionReason.NO_CANDIDATE
        if facts.pid == 1:
            return RejectionReason.PID_ONE
        if facts.pid in self.protected_pids:
            return RejectionReason.SELF_KILL_GUARD
        if descriptor.service_type is ServiceType.UNKNOWN:
            return RejectionReason.UNKNOWN_SERVICE_TYPE

        joined = " ".join(facts.command_line).lower()
        if any(hint in joined for hint in _CRITICAL_COMMAND_HINTS):
            return RejectionReason.CRITICAL_PROCESS

        if any("disappeared" in e for e in facts.read_errors):
            return RejectionReason.PROCESS_DISAPPEARED

        # Kernel threads expose neither cmdline nor exe.
        if not facts.command_line and not facts.executable:
            return RejectionReason.KERNEL_THREAD

        # Location is the primary ownership anchor and is mandatory.
        if cwd is None:
            return RejectionReason.CWD_UNREADABLE
        if not self._is_under(cwd, self.base_dir_resolved):
            return RejectionReason.CWD_OUTSIDE_BASE_DIR

        if expected_dir is None or not expected_dir.is_dir():
            return RejectionReason.EXPECTED_DIR_MISSING

        if cwd != expected_dir and not self._is_under(cwd, expected_dir):
            return RejectionReason.CWD_WRONG_SERVICE

        # The port matches yet the location is not the expected service root:
        # contradictory, therefore untrusted.
        if port_matches and cwd != expected_dir:
            return RejectionReason.CONTRADICTORY_EVIDENCE

        return None

    def verify(
        self,
        descriptor: ServiceDescriptor,
        facts: ProcessFacts,
        *,
        ancestors: Sequence[tuple[Sequence[str], str | None]] = (),
    ) -> OwnershipVerdict:
        """Grade the candidate process described by ``facts``.

        Evidence booleans are computed first and **preserved even when the
        candidate is rejected**, so the audit trail can show *why* (for example
        "port matched but cwd did not").  Only the grade is fail-closed: a
        rejected candidate is always ``NONE`` and never owns anything.
        """
        # ---- raw evidence (order-independent, never raises) ----------- #

        cwd = self._resolve(facts.cwd)
        expected_dir = descriptor.expected_dir_resolved

        port_matches = (
            descriptor.configured_port is not None
            and descriptor.configured_port in facts.listening_ports
        )
        cwd_matches = bool(cwd is not None and expected_dir is not None
                           and cwd == expected_dir)
        command_matches = command_matches_type(facts.command_line, descriptor.service_type)
        executable_matches = executable_matches_type(facts.executable, descriptor.service_type)
        ancestry_matches = self.ancestry_proves_workspace(
            self_argv=facts.command_line, ancestors=ancestors)

        evidence: list[str] = []
        if cwd is not None:
            evidence.append(f"cwd={cwd}")
        if expected_dir is not None:
            evidence.append(f"expected_dir={expected_dir}")
        if descriptor.configured_port is not None:
            evidence.append(f"configured_port={descriptor.configured_port}")
        evidence.append(f"listening_ports={sorted(facts.listening_ports)}")
        if port_matches:
            evidence.append("port_matches")
        if cwd_matches:
            evidence.append("cwd_is_expected_service_dir")
        if command_matches:
            evidence.append(f"command_matches:{descriptor.service_type.value}")
        if executable_matches:
            evidence.append(f"executable_matches:{facts.exe_basename}")
        if ancestry_matches:
            evidence.append("workspace_lineage_proven")
        if facts.read_errors:
            evidence.append(f"read_errors={list(facts.read_errors)}")

        raw = dict(
            executable_matches=executable_matches,
            cwd_matches=cwd_matches,
            port_matches=port_matches,
            command_matches=command_matches,
            ancestry_matches=ancestry_matches,
        )

        # ---- hard rejections ------------------------------------------ #

        rejection = self._hard_rejection(descriptor, facts, cwd, expected_dir,
                                         port_matches=port_matches)
        if rejection is not None:
            evidence.append(f"rejected:{rejection.value}")
            return OwnershipVerdict(
                confidence=Confidence.NONE,
                owned=False,
                evidence=tuple(evidence),
                rejection_reason=rejection.value,
                **raw,
            )

        # ---- grading -------------------------------------------------- #
        # HIGH is assembled directly from primary evidence; nothing is ever
        # promoted to it afterwards.

        primary_all = port_matches and cwd_matches and command_matches and executable_matches
        lineage_ok = ancestry_matches or not self.require_ancestry_for_high

        if primary_all and lineage_ok:
            return OwnershipVerdict(
                confidence=Confidence.HIGH, owned=True,
                evidence=tuple(evidence), **raw)

        if primary_all and not lineage_ok:
            evidence.append("lineage_not_proven")
            return OwnershipVerdict(
                confidence=Confidence.MEDIUM, owned=True,
                evidence=tuple(evidence), **raw)

        if cwd_matches and command_matches and executable_matches and not port_matches:
            # Right place, right command, not listening on the configured port
            # (still starting up, or bound elsewhere).
            evidence.append("port_not_listening")
            return OwnershipVerdict(
                confidence=Confidence.MEDIUM, owned=True,
                evidence=tuple(evidence), **raw)

        matched = sum((port_matches, cwd_matches, command_matches, executable_matches))
        if cwd_matches and matched >= 2:
            evidence.append(f"partial_evidence:{matched}/4")
            return OwnershipVerdict(
                confidence=Confidence.MEDIUM, owned=True,
                evidence=tuple(evidence), **raw)

        if cwd_matches or (port_matches and command_matches):
            evidence.append("insufficient_evidence")
            return OwnershipVerdict(
                confidence=Confidence.LOW, owned=False,
                evidence=tuple(evidence), **raw)

        evidence.append("no_aligned_evidence")
        return OwnershipVerdict(
            confidence=Confidence.NONE, owned=False,
            evidence=tuple(evidence),
            rejection_reason="no_aligned_evidence", **raw)


def select_candidate(identities: Sequence["object"]) -> tuple[object | None, str | None]:
    """Pick at most one candidate; refuse when the choice is ambiguous.

    Returns ``(identity, rejection_reason)``.  When several PIDs listen on the
    expected port we must **not** pick arbitrarily: an arbitrary pick is exactly
    the failure mode this phase exists to remove.
    """
    candidates = [i for i in identities if getattr(i, "pid", 0)]
    if not candidates:
        return None, RejectionReason.NO_CANDIDATE.value
    if len(candidates) > 1:
        return None, RejectionReason.AMBIGUOUS_CANDIDATES.value
    return candidates[0], None
